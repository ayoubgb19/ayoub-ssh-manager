#!/usr/bin/env bash
set -Eeuo pipefail
[[ ${EUID} -eq 0 ]] || { echo "Run with sudo"; exit 1; }
[[ -f /etc/ayoub-new-manager/settings.json ]] || { echo "Manager not installed"; exit 1; }
[[ -f /etc/caddy/Caddyfile && -f /usr/local/etc/xray/config.json ]] || { echo "Missing Caddy/Xray config"; exit 1; }
command -v caddy >/dev/null && [[ -x /usr/local/bin/xray ]] || { echo "Caddy or Xray missing"; exit 1; }
domain="$(python3 -c 'import json;print(json.load(open("/etc/ayoub-new-manager/settings.json"))["domain"])')"
[[ "$domain" =~ ^[a-zA-Z0-9.-]+$ ]] || exit 1
echo "Upgrade will configure port 80 WS (unencrypted) and port 443 gRPC TLS for $domain."
read -r -p "Proceed? [y/N]: " yes
[[ "$yes" =~ ^[Yy]$ ]] || exit 0
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
cp -a /etc/caddy/Caddyfile "$tmp/Caddyfile.old"
cp -a /usr/local/etc/xray/config.json "$tmp/xray.old"
cp -a /usr/local/bin/ayoub-new-manager "$tmp/manager.old"
curl -fLsS https://raw.githubusercontent.com/ayoubgb19/ayoub-ssh-manager/main/manager.py -o "$tmp/manager.py"
python3 -m py_compile "$tmp/manager.py"
# Only upgrade a Caddyfile generated by this project; avoid modifying unrelated sites.
grep -Fq 'respond "Ayoub SSH Manager" 200' /etc/caddy/Caddyfile || { echo "Caddyfile is custom; refusing automatic modification"; exit 1; }
if grep -Fq '@vmess_grpc' /etc/caddy/Caddyfile; then
 echo "gRPC Caddy routes already exist"
else
 python3 - "$domain" "$tmp/Caddyfile.old" "$tmp/Caddyfile.new" <<'PY'
import sys
domain,src,dst=sys.argv[1:]
c=open(src).read()
routes=''
for p,port in [('vmess',10101),('vless',10102),('trojan',10103)]:
 routes+=f' @{p}_grpc path /{p}-grpc/*\n handle @{p}_grpc {{\n  reverse_proxy h2c://127.0.0.1:{port}\n }}\n'
c=c.replace(' respond "Ayoub SSH Manager" 200',routes+' respond "Ayoub SSH Manager" 200',1)
c+=f"""
http://{domain} {{
 @vmess path /vmess
 handle @vmess {{
  reverse_proxy 127.0.0.1:10001
 }}
 @vless path /vless
 handle @vless {{
  reverse_proxy 127.0.0.1:10002
 }}
 @trojan path /trojan
 handle @trojan {{
  reverse_proxy 127.0.0.1:10003
 }}
 respond "Ayoub SSH Manager HTTP" 200
}}
"""
open(dst,'w').write(c)
PY
fi
if [[ -f "$tmp/Caddyfile.new" ]]; then caddy validate --adapter caddyfile --config "$tmp/Caddyfile.new"; fi
python3 - "$tmp/manager.py" "$tmp/xray.new.json" <<'PY'
import sys,importlib.util,json
spec=importlib.util.spec_from_file_location('mgr',sys.argv[1]);m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
with open(sys.argv[2],'w') as f:json.dump(m.xray_config(m.db()),f,indent=2)
PY
/usr/local/bin/xray run -test -config "$tmp/xray.new.json"
rollback() {
 cp -a "$tmp/Caddyfile.old" /etc/caddy/Caddyfile
 cp -a "$tmp/xray.old" /usr/local/etc/xray/config.json
 cp -a "$tmp/manager.old" /usr/local/bin/ayoub-new-manager
 systemctl restart xray caddy || true
 echo "Upgrade failed; previous files restored" >&2
}
trap 'rollback; rm -rf "$tmp"' ERR
if [[ -f "$tmp/Caddyfile.new" ]]; then install -m 644 "$tmp/Caddyfile.new" /etc/caddy/Caddyfile; fi
install -m 644 "$tmp/xray.new.json" /usr/local/etc/xray/config.json
install -m 755 "$tmp/manager.py" /usr/local/bin/ayoub-new-manager
systemctl restart xray caddy
systemctl is-active --quiet xray
systemctl is-active --quiet caddy
trap - ERR
echo "Upgrade applied. gRPC TLS on 443, non-TLS WS on 80."
echo "WARNING: non-TLS traffic is unencrypted. Verify ports 80/443 and test from client."
